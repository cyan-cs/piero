"""Writes src/text/wf_width_ambiguous.h: the East Asian Ambiguous ranges.

  python tools/make_ambiguous_width.py > src/text/wf_width_ambiguous.h

The table is the scalars whose East_Asian_Width is "A" in the Unicode data this
Python carries. wf_width.c uses it only when `[terminal] ambiguous_width = 2`:
a terminal set to draw ambiguous characters wide (common with Japanese
settings) then gets the same cell count from piero as it draws. Its Unicode
version must match the other width tables in wf_width.c (15.0).
"""
import sys
import unicodedata


def ranges():
    start = None
    last = None
    for cp in range(0x110000):
        ambiguous = unicodedata.east_asian_width(chr(cp)) == "A"
        if ambiguous and start is None:
            start = cp
        elif not ambiguous and start is not None:
            yield start, cp - 1
            start = None
        last = cp
    if start is not None:
        yield start, last


def main():
    version = unicodedata.unidata_version
    if version.split(".")[0] != "15":
        sys.exit("Unicode %s, but wf_width.c is Unicode 15" % version)
    out = ["/* Generated by tools/make_ambiguous_width.py: do not edit. */",
           "#ifndef WF_WIDTH_AMBIGUOUS_H",
           "#define WF_WIDTH_AMBIGUOUS_H",
           "",
           "/* East_Asian_Width=A, Unicode %s */" % version,
           "/* clang-format off */",
           "static const Range ambiguous[] = {"]
    for lo, hi in ranges():
        out.append("\t{0x%04X, 0x%04X}," % (lo, hi))
    out += ["};", "/* clang-format on */", "", "#endif", ""]
    # bytes: the repository is LF, whatever the platform's text mode does
    sys.stdout.buffer.write("\n".join(out).encode("ascii"))


main()
